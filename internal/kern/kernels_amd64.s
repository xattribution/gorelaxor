DATA expc<>+52(SB)/4, $0x41100000 // 9
DATA expc<>+56(SB)/4, $0xc1100000 // -9
DATA expc<>+60(SB)/4, $0x40000000 // 2
DATA expc<>+64(SB)/4, $0x0000007f // 127 (integer)
GLOBL expc<>(SB), RODATA|NOPTR, $68

// EXP8 computes Y0 = exp(Y0) for 8 floats, using Y1-Y3 and the constants
// broadcast in Y8-Y15 and Y7 (127). Inputs are clamped to [-87, 88].
#define EXP8 \
	VMAXPS Y12, Y0, Y0 \
	VMINPS Y13, Y0, Y0 \
	VMULPS Y8, Y0, Y1 \
	VROUNDPS $0, Y1, Y1 \
	VFNMADD231PS Y9, Y1, Y0 \
	VFNMADD231PS Y10, Y1, Y0 \
	VMOVAPS Y11, Y2 \
	VFMADD213PS Y14, Y0, Y2 \
	VBROADCASTSS expc<>+20(SB), Y3 \
	VFMADD213PS Y3, Y0, Y2 \
	VBROADCASTSS expc<>+24(SB), Y3 \
	VFMADD213PS Y3, Y0, Y2 \
	VBROADCASTSS expc<>+28(SB), Y3 \
	VFMADD213PS Y3, Y0, Y2 \
	VFMADD213PS Y15, Y0, Y2 \
	VFMADD213PS Y15, Y0, Y2 \
	VCVTPS2DQ Y1, Y1 \
	VPADDD Y7, Y1, Y1 \
	VPSLLD $23, Y1, Y1 \
	VMULPS Y1, Y2, Y0

#define EXPCONST \
	VBROADCASTSS expc<>+0(SB), Y8 \
	VBROADCASTSS expc<>+4(SB), Y9 \
	VBROADCASTSS expc<>+8(SB), Y10 \
	VBROADCASTSS expc<>+12(SB), Y11 \
	VBROADCASTSS expc<>+36(SB), Y12 \
	VBROADCASTSS expc<>+40(SB), Y13 \
	VBROADCASTSS expc<>+16(SB), Y14 \
	VBROADCASTSS expc<>+32(SB), Y15 \
	VPBROADCASTD expc<>+64(SB), Y7

// func expSubAVX(x *float32, n int, mx float32) float32
// x[i] = exp(x[i]-mx) for n a multiple of 8; returns the sum.
TEXT ·expSubAVX(SB), NOSPLIT, $0-28
	MOVQ x+0(FP), SI
	MOVQ n+8(FP), CX
	VBROADCASTSS mx+16(FP), Y6
	EXPCONST
	VXORPS Y5, Y5, Y5
	SHRQ $3, CX
	JEQ edone
eloop:
	VMOVUPS (SI), Y0
	VSUBPS Y6, Y0, Y0
	EXP8
	VMOVUPS Y0, (SI)
	VADDPS Y0, Y5, Y5
	ADDQ $32, SI
	DECQ CX
	JNZ eloop
edone:
	VEXTRACTF128 $1, Y5, X0
	VADDPS X0, X5, X5
	VHADDPS X5, X5, X5
	VHADDPS X5, X5, X5
	VMOVSS X5, ret+24(FP)
	VZEROUPPER
	RET

// func geluAVX(x *float32, n int)
// GELU in place (tanh form) for n a multiple of 8.
TEXT ·geluAVX(SB), NOSPLIT, $0-16
	MOVQ x+0(FP), SI
	MOVQ n+8(FP), CX
	EXPCONST
	SHRQ $3, CX
	JEQ gdone
gloop:
	VMOVUPS (SI), Y4
	// u = c*v*(1 + 0.044715 v^2), clamped to [-9, 9]
	VMULPS Y4, Y4, Y5
	VBROADCASTSS expc<>+48(SB), Y6
	VFMADD213PS Y15, Y6, Y5
	VMULPS Y4, Y5, Y5
	VBROADCASTSS expc<>+44(SB), Y6
	VMULPS Y6, Y5, Y5
	VBROADCASTSS expc<>+52(SB), Y6
	VMINPS Y6, Y5, Y5
	VBROADCASTSS expc<>+56(SB), Y6
	VMAXPS Y6, Y5, Y5
	// tanh(u) = 1 - 2/(exp(2u)+1)
	VADDPS Y5, Y5, Y0
	EXP8
	VADDPS Y15, Y0, Y0
	VBROADCASTSS expc<>+60(SB), Y6
	VDIVPS Y0, Y6, Y0
	VSUBPS Y0, Y15, Y0
	// 0.5*v*(1+t)
	VADDPS Y15, Y0, Y0
	VMULPS Y4, Y0, Y0
	VBROADCASTSS expc<>+28(SB), Y6
	VMULPS Y6, Y0, Y0
	VMOVUPS Y0, (SI)
	ADDQ $32, SI
	DECQ CX
	JNZ gloop
gdone:
	VZEROUPPER
	RET

// func dot4q8avx(x *float32, w *byte, ld int, nb int, out *[4]float32)
// out[r] = Σ x[i]·w_r[i] for r = 0..3, where row r starts at w+r*ld and
// holds nb Q8_0 blocks: a float16 scale, then 32 int8 values.
TEXT ·dot4q8avx(SB), NOSPLIT, $0-40
	MOVQ x+0(FP), SI
	MOVQ w+8(FP), DX
	MOVQ ld+16(FP), R8
	MOVQ nb+24(FP), CX
	MOVQ out+32(FP), DI
	LEAQ (DX)(R8*1), R11
	LEAQ (DX)(R8*2), R12
	LEAQ (R11)(R8*2), R10
	VXORPS Y8, Y8, Y8
	VXORPS Y9, Y9, Y9
	VXORPS Y10, Y10, Y10
	VXORPS Y11, Y11, Y11
	TESTQ CX, CX
	JEQ qdone

qloop:
	VMOVUPS (SI), Y0
	VMOVUPS 32(SI), Y1
	VMOVUPS 64(SI), Y2
	VMOVUPS 96(SI), Y3

#define Q8ROW(R, acc) \
	VPMOVSXBD 2(R), Y4 \
	VCVTDQ2PS Y4, Y4 \
	VMULPS Y0, Y4, Y5 \
	VPMOVSXBD 10(R), Y4 \
	VCVTDQ2PS Y4, Y4 \
	VFMADD231PS Y1, Y4, Y5 \
	VPMOVSXBD 18(R), Y4 \
	VCVTDQ2PS Y4, Y4 \
	VFMADD231PS Y2, Y4, Y5 \
	VPMOVSXBD 26(R), Y4 \
	VCVTDQ2PS Y4, Y4 \
	VFMADD231PS Y3, Y4, Y5 \
	VPBROADCASTW (R), X6 \
	VCVTPH2PS X6, Y6 \
	VFMADD231PS Y6, Y5, acc

	Q8ROW(DX, Y8)
	Q8ROW(R11, Y9)
	Q8ROW(R12, Y10)
	Q8ROW(R10, Y11)
	ADDQ $128, SI
	ADDQ $34, DX
	ADDQ $34, R11
	ADDQ $34, R12
	ADDQ $34, R10
	DECQ CX
	JNZ qloop

qdone:
	HSUM(Y8, X8, 0)
	HSUM(Y9, X9, 4)
	HSUM(Y10, X10, 8)
	HSUM(Y11, X11, 12)
	VZEROUPPER
	RET

// func dequantq8avx(dst *float32, q *byte, nb int)
// dst[0:32*nb] = the nb Q8_0 blocks at q, widened.
TEXT ·dequantq8avx(SB), NOSPLIT, $0-24
	MOVQ dst+0(FP), DI
	MOVQ q+8(FP), SI
	MOVQ nb+16(FP), CX
	TESTQ CX, CX
	JEQ ddone

dloop:
	VPBROADCASTW (SI), X6
	VCVTPH2PS X6, Y6
	VPMOVSXBD 2(SI), Y0
	VPMOVSXBD 10(SI), Y1
	VPMOVSXBD 18(SI), Y2
	VPMOVSXBD 26(SI), Y3
	VCVTDQ2PS Y0, Y0
	VCVTDQ2PS Y1, Y1
	VCVTDQ2PS Y2, Y2
	VCVTDQ2PS Y3, Y3
	VMULPS Y6, Y0, Y0
	VMULPS Y6, Y1, Y1
	VMULPS Y6, Y2, Y2
	VMULPS Y6, Y3, Y3
	VMOVUPS Y0, (DI)
	VMOVUPS Y1, 32(DI)
	VMOVUPS Y2, 64(DI)
	VMOVUPS Y3, 96(DI)
	ADDQ $34, SI
	ADDQ $128, DI
	DECQ CX
	JNZ dloop

ddone:
	VZEROUPPER
	RET

// func siluAVX(x *float32, n int)
