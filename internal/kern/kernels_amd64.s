// func k6x16avx(k int, a *float32, lda int, b *float32, c *float32, ldc int)
// C[6][16] += A[6][k] · B[k][16], B packed row-major, strides in elements.
TEXT ·k6x16avx(SB), NOSPLIT, $0-48
	MOVQ k+0(FP), CX
	MOVQ a+8(FP), SI
	MOVQ lda+16(FP), R8
	SHLQ $2, R8
	MOVQ b+24(FP), DX
	MOVQ c+32(FP), DI
	MOVQ ldc+40(FP), R9
	SHLQ $2, R9
	LEAQ (SI)(R8*2), R10
	ADDQ R8, R10
	VXORPS Y4, Y4, Y4
	VXORPS Y5, Y5, Y5
	VXORPS Y6, Y6, Y6
	VXORPS Y7, Y7, Y7
	VXORPS Y8, Y8, Y8
	VXORPS Y9, Y9, Y9
	VXORPS Y10, Y10, Y10
	VXORPS Y11, Y11, Y11
	VXORPS Y12, Y12, Y12
	VXORPS Y13, Y13, Y13
	VXORPS Y14, Y14, Y14
	VXORPS Y15, Y15, Y15
	TESTQ CX, CX
	JEQ store

loop:
	VMOVUPS (DX), Y0
	VMOVUPS 32(DX), Y1
	VBROADCASTSS (SI), Y2
	VFMADD231PS Y0, Y2, Y4
	VFMADD231PS Y1, Y2, Y5
	VBROADCASTSS (SI)(R8*1), Y3
	VFMADD231PS Y0, Y3, Y6
	VFMADD231PS Y1, Y3, Y7
	VBROADCASTSS (SI)(R8*2), Y2
	VFMADD231PS Y0, Y2, Y8
	VFMADD231PS Y1, Y2, Y9
	VBROADCASTSS (R10), Y3
	VFMADD231PS Y0, Y3, Y10
	VFMADD231PS Y1, Y3, Y11
	VBROADCASTSS (R10)(R8*1), Y2
	VFMADD231PS Y0, Y2, Y12
	VFMADD231PS Y1, Y2, Y13
	VBROADCASTSS (R10)(R8*2), Y3
	VFMADD231PS Y0, Y3, Y14
	VFMADD231PS Y1, Y3, Y15
	ADDQ $4, SI
	ADDQ $4, R10
	ADDQ $64, DX
	DECQ CX
	JNZ loop

store:
	LEAQ (DI)(R9*2), R11
	ADDQ R9, R11
	VADDPS (DI), Y4, Y4
	VMOVUPS Y4, (DI)
	VADDPS 32(DI), Y5, Y5
	VMOVUPS Y5, 32(DI)
	VADDPS (DI)(R9*1), Y6, Y6
	VMOVUPS Y6, (DI)(R9*1)
	VADDPS 32(DI)(R9*1), Y7, Y7
	VMOVUPS Y7, 32(DI)(R9*1)
	VADDPS (DI)(R9*2), Y8, Y8
	VMOVUPS Y8, (DI)(R9*2)
	VADDPS 32(DI)(R9*2), Y9, Y9
	VMOVUPS Y9, 32(DI)(R9*2)
	VADDPS (R11), Y10, Y10
	VMOVUPS Y10, (R11)
	VADDPS 32(R11), Y11, Y11
	VMOVUPS Y11, 32(R11)
	VADDPS (R11)(R9*1), Y12, Y12
	VMOVUPS Y12, (R11)(R9*1)
	VADDPS 32(R11)(R9*1), Y13, Y13
	VMOVUPS Y13, 32(R11)(R9*1)
	VADDPS (R11)(R9*2), Y14, Y14
	VMOVUPS Y14, (R11)(R9*2)
	VADDPS 32(R11)(R9*2), Y15, Y15
	VMOVUPS Y15, 32(R11)(R9*2)
	VZEROUPPER
	RET

#define HSUM(Y, X, off) \
	VEXTRACTF128 $1, Y, X0 \
	VADDPS X0, X, X \
	VHADDPS X, X, X \
	VHADDPS X, X, X \
	VMOVSS X, off(DI)

// func dot4f16avx(x *float32, w *uint16, ld int, k int, out *[4]float32)
// out[r] = Σ x[i]·w[r*ld+i] for r = 0..3; k is a multiple of 16.
TEXT ·dot4f16avx(SB), NOSPLIT, $0-40
	MOVQ x+0(FP), SI
	MOVQ w+8(FP), DX
	MOVQ ld+16(FP), R8
	SHLQ $1, R8
	MOVQ k+24(FP), CX
	MOVQ out+32(FP), DI
	LEAQ (DX)(R8*2), R10
	ADDQ R8, R10
	VXORPS Y4, Y4, Y4
	VXORPS Y5, Y5, Y5
	VXORPS Y6, Y6, Y6
	VXORPS Y7, Y7, Y7
	VXORPS Y8, Y8, Y8
	VXORPS Y9, Y9, Y9
	VXORPS Y10, Y10, Y10
	VXORPS Y11, Y11, Y11
	SHRQ $4, CX
	JEQ hdone

hloop:
	VMOVUPS (SI), Y0
	VMOVUPS 32(SI), Y12
	VCVTPH2PS (DX), Y1
	VFMADD231PS Y0, Y1, Y4
	VCVTPH2PS 16(DX), Y13
	VFMADD231PS Y12, Y13, Y8
	VCVTPH2PS (DX)(R8*1), Y2
	VFMADD231PS Y0, Y2, Y5
	VCVTPH2PS 16(DX)(R8*1), Y14
	VFMADD231PS Y12, Y14, Y9
	VCVTPH2PS (DX)(R8*2), Y3
	VFMADD231PS Y0, Y3, Y6
	VCVTPH2PS 16(DX)(R8*2), Y15
	VFMADD231PS Y12, Y15, Y10
	VCVTPH2PS (R10), Y1
	VFMADD231PS Y0, Y1, Y7
	VCVTPH2PS 16(R10), Y13
	VFMADD231PS Y12, Y13, Y11
	ADDQ $64, SI
	ADDQ $32, DX
	ADDQ $32, R10
	DECQ CX
	JNZ hloop

hdone:
	VADDPS Y8, Y4, Y4
	VADDPS Y9, Y5, Y5
	VADDPS Y10, Y6, Y6
	VADDPS Y11, Y7, Y7
	HSUM(Y4, X4, 0)
	HSUM(Y5, X5, 4)
	HSUM(Y6, X6, 8)
	HSUM(Y7, X7, 12)
	VZEROUPPER
	RET

