// func reluAVX(x *float32, n int)
// x = max(x, 0) for n a multiple of 8.
TEXT ·reluAVX(SB), NOSPLIT, $0-16
	MOVQ x+0(FP), SI
	MOVQ n+8(FP), CX
	VXORPS Y1, Y1, Y1
	SHRQ $3, CX
	JEQ rdone
rloop:
	VMAXPS (SI), Y1, Y0
	VMOVUPS Y0, (SI)
	ADDQ $32, SI
	DECQ CX
	JNZ rloop
rdone:
	VZEROUPPER
	RET
